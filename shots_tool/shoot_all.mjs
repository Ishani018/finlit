import { chromium } from 'playwright';
import fs from 'fs';
const out = '/Users/ishani/Desktop/finlit/shots_tool/raw';
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 430, height: 860 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
p.on('pageerror', e => console.log('PAGEERR', e.message.slice(0, 300)));
await p.goto('http://localhost:4173');
await p.waitForTimeout(5000);
const shot = async n => { await p.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n); };
const click = async (t, o = {}) => { try { await p.getByText(t, { exact: !!o.exact }).first().click({ timeout: 4000 }); } catch { console.log('MISS', t); } await p.waitForTimeout(o.wait || 1500); };
await shot('01_entry');
await click('TAP TO BEGIN');
await shot('02_select');
await p.mouse.click(120, 330); await p.waitForTimeout(1200);
await shot('03_profile');
await click('BEGIN JOURNEY');
await p.getByPlaceholder('Enter your name...').fill('Jane Doe');
await click('Day'); await shot('04_day_dropdown');
await p.getByText('15', { exact: true }).first().click(); await p.waitForTimeout(400);
await click('Month'); await p.getByText('Mar (03)').click(); await p.waitForTimeout(400);
await click('Year'); await p.getByText('2002', { exact: true }).click(); await p.waitForTimeout(600);
await shot('05_name_dob');
await click('BEGIN', { exact: true }); await p.waitForTimeout(2500);
await shot('06_intro');
await click('BEGIN', { exact: true }); await p.waitForTimeout(2500);
await shot('07_home');
await click('CAREER', { exact: true });
await shot('08_career');
await click('JOBS', { exact: true });
await shot('09_jobs');
await click('MONEY', { exact: true });
await shot('10_money');
await click('INVEST', { exact: true }); await p.waitForTimeout(1500);
await shot('11_invest');
await click('MONEY', { exact: true });
await click('BANK', { exact: true }); await p.waitForTimeout(1500);
await shot('12_bank');
await click('FAMILY', { exact: true });
await shot('13_family');
await b.close();
