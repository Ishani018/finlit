import { chromium } from 'playwright';
import fs from 'fs';
const out = '/Users/ishani/Desktop/finlit/shots_tool/raw';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 430, height: 860 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
p.on('pageerror', e => console.log('PAGEERR', e.message.slice(0, 300)));
await p.goto('http://localhost:4173');
await p.waitForTimeout(5000);
const txt = async () => (await p.innerText('body')).replace(/\s+/g, ' ').slice(0, 400);
const shot = async n => { await p.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n, '|', await txt()); };
const click = async t => { await p.getByText(t, { exact: false }).first().click({ timeout: 5000 }); await p.waitForTimeout(1500); };
await click('TAP TO BEGIN');
await p.mouse.click(120, 330); await p.waitForTimeout(1200);
await click('BEGIN JOURNEY');
await p.getByPlaceholder('Enter your name...').fill('Ishani');
await shot('04_name');
await click('Day'); await shot('05_day_dropdown');
await p.getByText('15', { exact: true }).first().click(); await p.waitForTimeout(500);
await click('Month'); await p.getByText('Mar (03)').click(); await p.waitForTimeout(500);
await click('Year'); await p.getByText('2002', { exact: true }).click(); await p.waitForTimeout(800);
await shot('06_name_filled');
await click('BEGIN');
await p.waitForTimeout(3000);
await shot('07_after_begin');
await b.close();
