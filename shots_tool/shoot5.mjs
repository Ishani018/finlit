import { chromium } from 'playwright';
const out = '/Users/ishani/Desktop/finlit/shots_tool/raw';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 430, height: 860 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
p.on('pageerror', e => console.log('PAGEERR', e.message.slice(0, 300)));
await p.goto('http://localhost:4173');
await p.waitForTimeout(5000);
const txt = async () => (await p.innerText('body')).replace(/\s+/g, ' ').slice(0, 300);
const shot = async n => { await p.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n, '|', await txt()); };
const click = async (t, o = {}) => { try { await p.getByText(t, { exact: !!o.exact }).first().click({ timeout: 4000 }); } catch { console.log('MISS', t); } await p.waitForTimeout(o.wait || 1500); };
await click('TAP TO BEGIN');
await p.mouse.click(120, 330); await p.waitForTimeout(1200);
await click('BEGIN JOURNEY');
await p.getByPlaceholder('Enter your name...').fill('Ishani');
await click('Day'); await p.getByText('15', { exact: true }).first().click(); await p.waitForTimeout(400);
await click('Month'); await p.getByText('Mar (03)').click(); await p.waitForTimeout(400);
await click('Year'); await p.getByText('2002', { exact: true }).click(); await p.waitForTimeout(500);
await click('BEGIN', { exact: true }); await p.waitForTimeout(2500);
await click('BEGIN', { exact: true }); await p.waitForTimeout(2500);
